// Bundles entry.ts and the production modules it imports into js/real.js (global `Real`). Run from the repo root: node docs/mockups/budget-builder-v5/build.mjs
// ponytail: TypeScript's own transpiler plus a 10-line module registry, because no bundler binary is installed here. Swap for esbuild if one is added.
import ts from 'typescript'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '../../..')
const mods = new Map()

function locate(spec, from) {
  const base = spec.startsWith('@/') ? join(repo, 'src', spec.slice(2)) : resolve(dirname(from), spec)
  const hit = [base + '.ts', base + '.tsx', join(base, 'index.ts')].find(existsSync)
  if (!hit) throw new Error(`cannot resolve ${spec} from ${from}`)
  return hit
}

function add(file) {
  if (mods.has(file)) return
  mods.set(file, null)
  let js = ts.transpileModule(readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, verbatimModuleSyntax: false } }).outputText
  js = js.replace(/require\("([^"]+)"\)/g, (_, spec) => {
    const dep = locate(spec, file)
    add(dep)
    return `__req(${JSON.stringify(dep.slice(repo.length + 1))})`
  })
  mods.set(file, js)
}

const entry = join(here, 'entry.ts')
add(entry)
const body = [...mods].map(([f, js]) => `${JSON.stringify(f.slice(repo.length + 1))}: function (exports, __req) {\n${js}\n}`).join(',\n')
const out = `/* Generated by build.mjs from src/lib/budget. Do not edit. */\n;(function (root) {\nconst defs = {\n${body}\n}\nconst cache = {}\nfunction __req(id) { if (!cache[id]) { cache[id] = {}; defs[id](cache[id], __req) } return cache[id] }\nroot.Real = __req(${JSON.stringify(entry.slice(repo.length + 1))})\n})(typeof globalThis !== 'undefined' ? globalThis : this)\n`
writeFileSync(join(here, 'js/real.js'), out)
console.log(`real.js: ${mods.size} modules, ${(out.length / 1024).toFixed(0)} KB`)
