#!/usr/bin/env python3
"""S3b: turns the dry-run diff (.claude/s3-diff.json, .claude/s3-steps.json; git-ignored) into scripts/qa/s3-apply-input.json,
the list that sms_s3_apply checks each live row against and the insert script books from. Log ids are cut to 8 characters,
users to 8; no text. Run: python3 scripts/qa/s3-gen-apply-input.py [exclude_prefix ...]  (excluded rows are dropped and listed
in the output's 'excluded')."""
import json, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
diff = {x['id']: x for x in json.load(open(root / '.claude/s3-diff.json'))}
steps = json.load(open(root / '.claude/s3-steps.json'))
excluded = set(sys.argv[1:])

# the report calls the via-card flag card_flag; the shipped flag with a prompt is model_kind_unproven
T5_FLAGS = ['model_kind_unproven']


def rtype(x):
    return x['type'].split(' ')[0]


def live_ex(x, extra):
    l = x['live'][0]
    ex = {
        'table': 'expenses' if l['t'] == 'E' else 'income_events', 'amount': l['amt'], 'currency': l['ccy'], 'day': l['day'],
        'refund_by': l['refund'][1], 'flags': l['flags'],
    }
    if l['t'] == 'E':
        ex['category'] = l['cat']
    ex.update(extra)
    return ex


rows = []
for step_name, step in (('step1', 1), ('step2', 2)):
    for i in steps[step_name]:
        if i in excluded:
            continue
        x = diff[i]
        t = rtype(x)
        base = {'prefix': i, 'usr': x['user'], 'rtype': t, 'step': step, 'ex': None, 'ins': None}
        prop = x['prop'][0] if x['prop'] else None
        if t in ('T6', 'T7b'):
            base['ins'] = prop
        elif t == 'T15':
            base['ex'] = live_ex(x, {'new_day': prop['day']})
        elif t in ('T1', 'T2a', 'T11', 'T3'):
            base['ex'] = live_ex(x, {})
        elif t == 'T2b':
            base['ex'] = live_ex(x, {'stamp_from_log': 'bfe884e3'})
        elif t == 'T4':
            if x['live'][0]['t'] == 'I':
                base['ex'] = live_ex(x, {})
                base['ins'] = prop
            else:
                base['ex'] = live_ex(x, {'flags_add': ['cash_deposit']})
        elif t == 'T5':
            base['ex'] = live_ex(x, {'flags_add': T5_FLAGS})
        elif t == 'T8':
            base['ex'] = live_ex(x, {})
            base['ins'] = prop
        elif t == 'T9':
            base['ex'] = live_ex(x, {'marker_log': '42136093', 'pair_log': '42136093'})
        else:
            raise SystemExit('unhandled type ' + t)
        base['eff'] = x['eff']
        rows.append(base)

out = {'source': 'S3-rerun.md (0087710d)', 'excluded': sorted(excluded), 'rows': rows}
(root / 'scripts/qa/s3-apply-input.json').write_text(json.dumps(out, indent=1) + '\n')
print(len(rows), 'rows;', sum(1 for r in rows if r['ex']), 'live repairs;', sum(1 for r in rows if r['ins']), 'inserts')

tpl = (root / 'scripts/qa/s3-apply-revert.template.sql').read_text()
(root / 'scripts/qa/sql/0283_s3_apply_revert.test.sql').write_text(tpl)
load = ("-- Loads scripts/qa/s3-apply-input.json into sms_s3_input (generated by scripts/qa/s3-gen-apply-input.py). Idempotent.\n"
        "delete from public.sms_s3_input;\ninsert into public.sms_s3_input\n"
        "select x.prefix, x.usr, x.rtype, x.step, x.ex, x.ins, x.eff from jsonb_to_recordset($j$" + json.dumps({'rows': rows}, separators=(',', ':')) +
        "$j$::jsonb -> 'rows') as x(prefix text, usr text, rtype text, step int, ex jsonb, ins jsonb, eff jsonb);\n")
(root / 'scripts/qa/sql/0283_s3_load_input.sql').write_text(load)
